"""Generate pinned Unicode 15 case-fold data and independent normalization vectors."""
import json
import sys
import unicodedata as u

assert u.unidata_version == '15.0.0', 'Run in the pinned Python 3.12 Docker image'
fold = {}
unassigned = []
vectors = []
start = None
for code in range(0x110000):
    char = chr(code)
    absent = u.category(char) in {'Cn', 'Cs'}
    if absent and start is None:
        start = code
    elif not absent and start is not None:
        unassigned.append([start, code - 1])
        start = None
    if absent:
        continue
    if char.casefold() != char:
        fold[char] = char.casefold()
    normalized = ' '.join(u.normalize('NFKC', char).casefold().split())
    if normalized != char:
        vectors.append([char, normalized])
if start is not None:
    unassigned.append([start, 0x10ffff])
if '--vectors' in sys.argv:
    print(json.dumps({'unicode_version': u.unidata_version, 'vectors': vectors}, ensure_ascii=False, indent=2))
else:
    print('// Generated by scripts/unicode-contract.py using Unicode 15.0.0. Do not edit.')
    print('// Unicode data license: see THIRD_PARTY_NOTICES.md.')
    print('export const fold: Readonly<Record<string,string>> = ' + json.dumps(fold, ensure_ascii=False, separators=(',', ':')) + ';')
    print('export const unassigned: readonly (readonly [number,number])[] = ' + json.dumps(unassigned, separators=(',', ':')) + ';')
